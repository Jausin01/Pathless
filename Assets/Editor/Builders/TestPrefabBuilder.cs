using Pathless.Dialogue;
using Pathless.Interaction;
using Pathless.Player;
using UnityEditor;
using UnityEditor.Animations;
using UnityEngine;
using UnityEngine.InputSystem;

namespace Pathless.EditorTools
{
    /// <summary>
    /// Builds the two prefabs used by the test scene: the Player and the simple NPC block.
    /// Run it from Tools > Pathless > Build Test Prefabs (or through "Build Everything").
    /// Running it again REPLACES the generated prefabs.
    /// </summary>
    public static class TestPrefabBuilder
    {
        /// <summary>Folder where the Player prefab is saved.</summary>
        private const string CharactersFolder = "Assets/Prefabs/Characters";

        /// <summary>Folder where the NPC block prefab is saved.</summary>
        private const string PropsFolder = "Assets/Prefabs/Props";

        /// <summary>Full path of the generated Player prefab.</summary>
        public const string PlayerPrefabPath = "Assets/Prefabs/Characters/Player.prefab";

        /// <summary>Full path of the generated NPC block prefab.</summary>
        public const string NpcBlockPrefabPath = "Assets/Prefabs/Props/NpcBlock.prefab";

        /// <summary>Full path of the generated sign prefab.</summary>
        public const string SignPrefabPath = "Assets/Prefabs/Props/Sign.prefab";

        /// <summary>The sprite used for the test sign.</summary>
        private const string SignSpritePath = "Assets/Art/Props/SignPost_Claude.png";

        /// <summary>The project's Input System asset, assigned to the player's input reader.</summary>
        private const string InputActionsPath = "Assets/Settings/InputSystem_Actions.inputactions";

        /// <summary>The sprite the player shows before the Animator starts (idle, facing South).</summary>
        private const string DefaultPlayerSpritePath = "Assets/Art/Characters/Player/Frames/south/Player_Walk_south_00.png";

        /// <summary>The block sprite used for the test NPCs.</summary>
        private const string NpcBlockSpritePath = "Assets/Art/Props/NpcBlock_Claude.png";

        /// <summary>Menu entry that builds only the prefabs (the animation controller must already exist).</summary>
        [MenuItem("Tools/Pathless/Build Test Prefabs")]
        public static void BuildFromMenu()
        {
            AnimatorController controller = AssetDatabase.LoadAssetAtPath<AnimatorController>(PlayerAnimationBuilder.ControllerPath);
            if (controller == null)
            {
                Debug.LogError("TestPrefabBuilder: Player.controller not found. Run 'Build Player Animations' first.");
                return;
            }

            BuildPlayerPrefab(controller);
            BuildNpcBlockPrefab();
            BuildSignPrefab();
        }

        /// <summary>
        /// Creates the Player prefab: sprite, Animator, physics body, feet collider and all player scripts.
        /// </summary>
        /// <param name="controller">The Animator Controller generated by PlayerAnimationBuilder.</param>
        /// <returns>The saved prefab asset, or null if something is missing.</returns>
        public static GameObject BuildPlayerPrefab(AnimatorController controller)
        {
            Sprite defaultSprite = AssetDatabase.LoadAssetAtPath<Sprite>(DefaultPlayerSpritePath);
            InputActionAsset inputActions = AssetDatabase.LoadAssetAtPath<InputActionAsset>(InputActionsPath);

            if (defaultSprite == null || inputActions == null)
            {
                Debug.LogError("TestPrefabBuilder: player sprite or InputSystem_Actions asset not found.");
                return null;
            }

            EditorAssetUtility.EnsureFolder(CharactersFolder);

            GameObject player = new GameObject("Player");
            player.tag = "Player";

            // Visuals: the Animator swaps the sprite of this renderer.
            SpriteRenderer spriteRenderer = player.AddComponent<SpriteRenderer>();
            spriteRenderer.sprite = defaultSprite;
            // Sort by the pivot (the feet / the base of the block), not by the sprite center.
            // With Y sorting this makes whoever stands lower on the screen draw in front.
            spriteRenderer.spriteSortPoint = SpriteSortPoint.Pivot;

            Animator animator = player.AddComponent<Animator>();
            animator.runtimeAnimatorController = controller;

            // Physics: dynamic body without gravity (top-down), no rotation, smooth movement for the camera.
            Rigidbody2D body = player.AddComponent<Rigidbody2D>();
            body.gravityScale = 0f;
            body.constraints = RigidbodyConstraints2D.FreezeRotation;
            body.interpolation = RigidbodyInterpolation2D.Interpolate;
            body.collisionDetectionMode = CollisionDetectionMode2D.Continuous;

            // Collider only around the feet (20 x 8 pixels) so the head can pass in front of walls (top-down feel).
            BoxCollider2D feetCollider = player.AddComponent<BoxCollider2D>();
            feetCollider.size = new Vector2(0.625f, 0.25f);
            feetCollider.offset = new Vector2(0f, 0.125f);

            // Scripts. The input reader goes first because the motor requires it.
            PlayerInputReader reader = player.AddComponent<PlayerInputReader>();
            EditorAssetUtility.SetReference(reader, "actions", inputActions);

            player.AddComponent<PlayerMotor>();
            player.AddComponent<PlayerFacing>();
            player.AddComponent<PlayerAnimatorDriver>();
            player.AddComponent<InteractionSensor>();

            GameObject prefab = PrefabUtility.SaveAsPrefabAsset(player, PlayerPrefabPath);
            Object.DestroyImmediate(player);

            Debug.Log("TestPrefabBuilder: Player prefab saved at " + PlayerPrefabPath);
            return prefab;
        }

        /// <summary>
        /// Creates the sign prefab: a small solid prop with a DialogueInteractable. Its conversation uses lines
        /// without a speaker (the "> text" lines of a .dialogue file), so the box shows centered with no portrait.
        /// </summary>
        /// <returns>The saved prefab asset, or null if the sign sprite is missing.</returns>
        public static GameObject BuildSignPrefab()
        {
            Sprite signSprite = AssetDatabase.LoadAssetAtPath<Sprite>(SignSpritePath);
            if (signSprite == null)
            {
                Debug.LogError("TestPrefabBuilder: sign sprite not found at " + SignSpritePath);
                return null;
            }

            EditorAssetUtility.EnsureFolder(PropsFolder);

            GameObject sign = new GameObject("Sign");

            SpriteRenderer spriteRenderer = sign.AddComponent<SpriteRenderer>();
            spriteRenderer.sprite = signSprite;
            spriteRenderer.spriteSortPoint = SpriteSortPoint.Pivot;

            // Only the post blocks the player (a thin box at the base).
            BoxCollider2D solidCollider = sign.AddComponent<BoxCollider2D>();
            solidCollider.size = new Vector2(0.4f, 0.3f);
            solidCollider.offset = new Vector2(0f, 0.15f);

            sign.AddComponent<DialogueInteractable>();

            GameObject prefab = PrefabUtility.SaveAsPrefabAsset(sign, SignPrefabPath);
            Object.DestroyImmediate(sign);

            Debug.Log("TestPrefabBuilder: sign prefab saved at " + SignPrefabPath);
            return prefab;
        }

        /// <summary>
        /// Creates the NPC block prefab: a solid block with a DialogueInteractable that starts a dialogue when interacted with.
        /// </summary>
        /// <returns>The saved prefab asset, or null if the block sprite is missing.</returns>
        public static GameObject BuildNpcBlockPrefab()
        {
            Sprite blockSprite = AssetDatabase.LoadAssetAtPath<Sprite>(NpcBlockSpritePath);
            if (blockSprite == null)
            {
                Debug.LogError("TestPrefabBuilder: block sprite not found at " + NpcBlockSpritePath);
                return null;
            }

            EditorAssetUtility.EnsureFolder(PropsFolder);

            GameObject block = new GameObject("NpcBlock");

            SpriteRenderer spriteRenderer = block.AddComponent<SpriteRenderer>();
            spriteRenderer.sprite = blockSprite;
            // Sort by the pivot (the feet / the base of the block), not by the sprite center.
            // With Y sorting this makes whoever stands lower on the screen draw in front.
            spriteRenderer.spriteSortPoint = SpriteSortPoint.Pivot;

            // Solid collider on the lower half of the block (the sprite pivot is at the bottom center).
            BoxCollider2D solidCollider = block.AddComponent<BoxCollider2D>();
            solidCollider.size = new Vector2(0.9f, 0.5f);
            solidCollider.offset = new Vector2(0f, 0.25f);

            block.AddComponent<DialogueInteractable>();

            GameObject prefab = PrefabUtility.SaveAsPrefabAsset(block, NpcBlockPrefabPath);
            Object.DestroyImmediate(block);

            Debug.Log("TestPrefabBuilder: NPC block prefab saved at " + NpcBlockPrefabPath);
            return prefab;
        }
    }
}
